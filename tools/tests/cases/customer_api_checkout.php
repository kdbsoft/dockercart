<?php
/**
 * Customer API checkout — cart scope, catalog model guard and the confirm gate.
 *
 * Pure unit coverage of the pieces the checkout flow rests on; the flow itself
 * needs the database and is verified against a running stack (see
 * docs/guide.md §21).
 *
 * @package    DockerCart
 * @subpackage Tests
 */

declare(strict_types=1);

use Dockercart\Api\CatalogModels;
use Dockercart\Api\CartScope;
use Dockercart\Api\CustomerPrincipal;
use Dockercart\Api\CustomerScopes;
use Dockercart\Api\StoreRoutes;

function store_api_registry(): \Registry {
	$registry = new \Registry();

	$config = new \Config();
	$config->set('config_language_id', 1);
	$config->set('config_customer_group_id', 1);
	$config->set('config_store_id', 0);

	$registry->set('config', $config);
	$registry->set('log', new \Log('test.log'));

	return $registry;
}

return [
	'store api checkout: a cart scope is a valid session id' => static function (): void {
		// Session::start() accepts [a-zA-Z0-9,-]{22,52}; the scope must fit or
		// the cart session cannot be started at all.
		Assert::true(CartScope::isValid('stp' . str_repeat('a', 28)), '31 chars must be valid');
		Assert::true(CartScope::isValid('stp' . str_repeat('0', 49)), '52 chars must be valid');

		Assert::false(CartScope::isValid('stp'), 'too short');
		Assert::false(CartScope::isValid('stp' . str_repeat('a', 50)), 'too long');
		Assert::false(CartScope::isValid('api' . str_repeat('a', 28)), 'wrong prefix');
		Assert::false(CartScope::isValid('stp' . str_repeat('A', 28)), 'uppercase is not generated by CartScope');
		Assert::false(CartScope::isValid(''), 'empty');
		Assert::false(CartScope::isValid("stp\n" . str_repeat('a', 27)), 'a newline is not a session id character');
	},

	'store api checkout: the catalog model loader refuses admin-tree collisions' => static function (): void {
		$registry = store_api_registry();

		// Class name collisions would be a fatal error (both trees declare the
		// class), so the loader must refuse them up front.
		foreach (['catalog/product', 'localisation/country', 'localisation/zone', 'setting/extension', 'tool/image'] as $route) {
			$failed = false;

			try {
				CatalogModels::load($registry, $route);
			} catch (\RuntimeException $exception) {
				$failed = true;
			}

			Assert::true($failed, 'loading ' . $route . ' must be refused');
			Assert::false($registry->has('model_' . str_replace('/', '_', $route)), $route . ' must not be registered');
		}
	},

	'store api checkout: the catalog model loader loads storefront extension models' => static function (): void {
		$registry = store_api_registry();

		$model = CatalogModels::load($registry, 'extension/total/sub_total');

		Assert::true(is_object($model));
		Assert::same('ModelExtensionTotalSubTotal', get_class($model));
		Assert::true($registry->has('model_extension_total_sub_total'), 'the model is registered under the loader key');

		// Loader::model() prefers an existing registry key, so a second call —
		// and any nested $this->load->model() — reuses the same instance.
		Assert::true($model === CatalogModels::load($registry, 'extension/total/sub_total'));

		$failed = false;

		try {
			CatalogModels::load($registry, 'extension/total/does_not_exist');
		} catch (\RuntimeException $exception) {
			$failed = true;
		}

		Assert::true($failed, 'a missing catalog model must fail loudly');
	},

	'store api checkout: the checkout surface needs the checkout scope only' => static function (): void {
		$prefixes = ['/v1/cart', '/v1/checkout', '/v1/addresses', '/v1/meta/countries'];

		foreach (StoreRoutes::table() as $entry) {
			$is_checkout = false;

			foreach ($prefixes as $prefix) {
				if (strpos($entry['path'], $prefix) === 0) {
					$is_checkout = true;
				}
			}

			if (!$is_checkout) {
				continue;
			}

			Assert::same(
				CustomerScopes::CHECKOUT_WRITE,
				$entry['scope'],
				$entry['method'] . ' ' . $entry['path'] . ' must require ' . CustomerScopes::CHECKOUT_WRITE
			);

			Assert::false($entry['public'], $entry['path'] . ' must not be public');
		}
	},

	'store api checkout: the cart scope is persisted once and reused' => static function (): void {
		$db = new FakeDb();

		$registry = store_api_registry();
		$registry->set('db', $db);

		// First call: no scope yet -> generated, written, re-read.
		$db->pushResult([]);
		$db->pushResult([['api_cart_scope' => 'stp' . str_repeat('a', 28)]]);

		$scope = CartScope::forCustomer($registry, 42);

		Assert::same('stp' . str_repeat('a', 28), $scope);
		Assert::true(CartScope::isValid($scope));

		$writes = array_values(array_filter($db->queries, static function (string $sql): ?bool {
			return stripos($sql, 'UPDATE `oc_customer`') === 0;
		}));

		Assert::count(1, $writes, 'exactly one scope write');

		// Second call: the stored scope is reused, nothing is written.
		$db->pushResult([['api_cart_scope' => $scope]]);

		Assert::same($scope, CartScope::forCustomer($registry, 42));

		$failed = false;

		try {
			CartScope::forCustomer($registry, 0);
		} catch (\RuntimeException $exception) {
			$failed = true;
		}

		Assert::true($failed, 'a customer id is required');
	},

	'store api checkout: the principal mirrors the reward points and credit balance' => static function (): void {
		$db = new FakeDb();

		$registry = store_api_registry();
		$registry->set('db', $db);

		$principal = new CustomerPrincipal([
			'customer_id'       => 7,
			'customer_group_id' => 3,
			'firstname'         => 'Ada',
			'lastname'          => 'Lovelace',
			'email'             => 'ada@example.com',
			'telephone'         => '+380000000000',
			'address_id'        => 4,
		], [CustomerScopes::CHECKOUT_WRITE], 11);

		$principal->setRegistry($registry);

		$db->pushResult([['total' => '120']]);
		$db->pushResult([['total' => '55.5000']]);

		Assert::same('120', $principal->getRewardPoints());
		Assert::same('55.5000', $principal->getBalance());

		// The storefront models read these through Cart\Customer's interface.
		Assert::same(7, $principal->getId());
		Assert::same(3, $principal->getGroupId());
		Assert::same(3, $principal->getCustomerGroupId());
		Assert::same(4, $principal->getAddressId());
		Assert::true($principal->isLogged());
		Assert::true($principal->can(CustomerScopes::CHECKOUT_WRITE));
		Assert::false($principal->can(CustomerScopes::ORDERS_READ));

		$failed = false;

		try {
			(new CustomerPrincipal(['customer_id' => 8], [], 1))->getBalance();
		} catch (\RuntimeException $exception) {
			$failed = true;
		}

		Assert::true($failed, 'a principal without a registry must fail loudly');
	},

	'store api checkout: the order is created only through the confirm endpoint' => static function (): void {
		foreach (StoreRoutes::table() as $entry) {
			if ($entry['method'] !== 'POST') {
				continue;
			}

			if ($entry['route'] !== 'store_api/orders') {
				continue;
			}

			throw new \TestFailure('POST ' . $entry['path'] . ' must not exist: orders are created by POST /v1/checkout/{id}/confirm');
		}

		$confirm = null;

		foreach (StoreRoutes::table() as $entry) {
			if ($entry['method'] === 'POST' && preg_match('#^/v1/checkout/\{checkout_id\}/confirm$#', $entry['path'])) {
				$confirm = $entry;
			}
		}

		Assert::true($confirm !== null, 'the confirm endpoint must stay registered');
		Assert::same('confirm', $confirm['action']);
		Assert::same('store_api/checkout', $confirm['route']);
	},
];
