<?php
/**
 * DockerCart admin REST API — front controller.
 *
 * Served as /api/v1/... (nginx rewrites to /api/index.php?_route_=/v1/...).
 * The `api` application (upload/system/config/api.php) reuses the admin MVC
 * tree, so the resource controllers live in upload/admin/controller/api/ and
 * call the regular admin models.
 *
 * @package    DockerCart
 * @subpackage Api
 */

declare(strict_types=1);

// Version
$version = '1.0.0';
$version_files = [
	dirname(__DIR__) . '/VERSION',
	dirname(__DIR__, 2) . '/VERSION'
];

foreach ($version_files as $version_file) {
	if (is_file($version_file)) {
		$file_version = trim((string)file_get_contents($version_file));

		if ($file_version !== '') {
			$version = $file_version;
			break;
		}
	}
}

define('VERSION', $version);
define('DOCKERCART_VERSION', $version);

// Configuration (generated by docker/entrypoint.sh from .env, exactly like
// upload/admin/config.php; it also defines DIR_API).
if (is_file(__DIR__ . '/config.php')) {
	/** @phpstan-ignore-next-line requireOnce.fileNotFound */
	require_once __DIR__ . '/config.php';
}

// Not configured: answer in JSON, never with an HTML error page.
if (!defined('DIR_SYSTEM')) {
	http_response_code(503);
	header('Content-Type: application/json; charset=utf-8');
	header('Cache-Control: no-store');

	echo json_encode([
		'error' => [
			'code'    => 'not_configured',
			'message' => 'DockerCart API is not configured. Check .env and api/config.php bootstrap.',
		],
	]);

	exit;
}

// Startup
require_once DIR_SYSTEM . 'startup.php';

start('api');
